export const EMOJI: Emoji[] = rows.map(([char, name, keywords]) => ({ char, name, keywords: keywords.split(' ') }));

// 0 = a whole word matches, 1 = a word starts with it, 2 = it appears inside a word; equal ranks keep catalogue order
export function searchEmoji(query: string): Emoji[] {
	const q = query.trim().toLowerCase();
	if (!q) return EMOJI;
	const rank = (e: Emoji): number => {
		const words = [...e.name.split(' '), ...e.keywords];
		if (words.includes(q)) return 0;
		if (words.some((w) => w.startsWith(q))) return 1;
		return words.some((w) => w.includes(q)) ? 2 : 3;
	};
	return EMOJI.map((e) => ({ e, r: rank(e) }))
		.filter(({ r }) => r < 3)
		.sort((a, b) => a.r - b.r)
		.map(({ e }) => e);
}
